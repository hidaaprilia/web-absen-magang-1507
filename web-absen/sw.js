const CACHE_NAME = 'absen-1507-shell-v6';
const SHELL_ASSETS = [
  '/',
  '/index.html',
  '/styles.css',
  '/config.js',
  '/logic.js',
  '/shared.js',
  '/app.js',
  '/manifest.webmanifest',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/apple-touch-icon.png'
];

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      return cache.addAll(SHELL_ASSETS);
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(
        keys
          .filter(function (k) { return k !== CACHE_NAME; })
          .map(function (k) { return caches.delete(k); })
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;

  var url = new URL(req.url);
  // Jangan pernah cache API Google Apps Script (data absensi & waktu server wajib live)
  if (url.origin !== self.location.origin) return;

  // Network-first agar pembaruan kode/config langsung diterima, fallback ke cache saat offline
  event.respondWith(
    fetch(req)
      .then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE_NAME).then(function (cache) {
            cache.put(req, copy);
          });
        }
        return res;
      })
      .catch(function () {
        return caches.match(req).then(function (cached) {
          return cached || (req.mode === 'navigate' ? caches.match('/index.html') : undefined);
        });
      })
  );
});
